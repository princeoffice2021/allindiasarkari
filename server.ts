import express from 'express';
import path from 'path';
import dotenv from 'dotenv';
import { createServer as createViteServer } from 'vite';

// Load environment variables
dotenv.config();

async function startServer() {
  const app = express();
  const PORT = 3000;

  // Middleware
  app.use(express.json({ limit: '10mb' }));

  // CORS for local development and production
  app.use((req, res, next) => {
    res.header('Access-Control-Allow-Credentials', 'true');
    res.header('Access-Control-Allow-Origin', '*');
    res.header('Access-Control-Allow-Methods', 'GET,OPTIONS,PATCH,DELETE,POST,PUT');
    res.header(
      'Access-Control-Allow-Headers',
      'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version, Authorization'
    );
    if (req.method === 'OPTIONS') {
      return res.status(200).end();
    }
    next();
  });

  // General Application Health Endpoint (Non-AI)
  app.get('/api/health', (req, res) => {
    res.json({
      status: 'ok',
      environment: process.env.NODE_ENV || 'production',
      time: new Date().toISOString(),
    });
  });

  // AI Sarkari Staff Endpoints (Server-side Research & Scanning)
  app.get('/api/ai-staff/health', (req, res) => {
    res.json({
      status: 'ok',
      module: 'AI Sarkari Staff',
      geminiConfigured: Boolean(process.env.GEMINI_API_KEY),
      time: new Date().toISOString(),
    });
  });

  // Get current status of AI Staff scheduler & today's batch
  app.get('/api/ai-staff/status', async (req, res) => {
    try {
      const { getSchedulerStatus } = await import('./server/aiStaffScheduler');
      res.json({ success: true, status: getSchedulerStatus() });
    } catch (err: any) {
      res.status(500).json({ success: false, error: err.message });
    }
  });

  // Update scheduler settings (frequency, scan time, timezone)
  app.post('/api/ai-staff/settings', async (req, res) => {
    try {
      const { updateSchedulerSettings } = await import('./server/aiStaffScheduler');
      const updated = updateSchedulerSettings(req.body);
      res.json({ success: true, status: updated });
    } catch (err: any) {
      res.status(500).json({ success: false, error: err.message });
    }
  });

  // Get recent daily batches
  app.get('/api/ai-staff/batches', async (req, res) => {
    try {
      const { getRecentBatches, getRecentReports } = await import('./server/aiStaffScheduler');
      res.json({
        success: true,
        batches: getRecentBatches(),
        reports: getRecentReports(),
      });
    } catch (err: any) {
      res.status(500).json({ success: false, error: err.message });
    }
  });

  // Get server-queued drafts generated by automated cron scans
  app.get('/api/ai-staff/drafts', async (req, res) => {
    try {
      const { getServerDraftsQueue } = await import('./server/aiStaffScheduler');
      res.json({
        success: true,
        drafts: getServerDraftsQueue(),
      });
    } catch (err: any) {
      res.status(500).json({ success: false, error: err.message });
    }
  });

  // Secure Cron Endpoint for Vercel Cron, Cloud Scheduler, or External Pingers
  const handleCronRequest = async (req: express.Request, res: express.Response) => {
    const authHeader = req.headers.authorization;
    const querySecret = req.query.secret as string | undefined;
    const configuredSecret = process.env.CRON_SECRET;

    // In production, CRON_SECRET is strictly mandatory
    if (process.env.NODE_ENV === 'production' && (!configuredSecret || configuredSecret.trim() === '')) {
      console.error('[Cron Security Error] CRON_SECRET is required in production environment.');
      return res.status(500).json({ success: false, error: 'Server misconfiguration: CRON_SECRET environment variable is missing.' });
    }

    // Verify secret if CRON_SECRET is configured
    if (configuredSecret && configuredSecret.trim() !== '') {
      const isAuthorized =
        authHeader === `Bearer ${configuredSecret}` ||
        querySecret === configuredSecret ||
        req.headers['x-cron-secret'] === configuredSecret;

      if (!isAuthorized) {
        console.warn('[Cron Auth] Unauthorized cron access attempt from', req.ip);
        return res.status(401).json({ success: false, error: 'Unauthorized cron request: Invalid or missing secret' });
      }
    } else {
      console.warn('[Cron Warning] CRON_SECRET is not configured. Running in development mode without token validation.');
    }

    try {
      const { runSchedulerScan } = await import('./server/aiStaffScheduler');
      console.log('[Cron Trigger] Executing scheduled scan via /api/cron/ai-staff-scan');
      const result = await runSchedulerScan('Vercel/External Scheduled Cron');

      res.json({
        success: true,
        message: 'Daily AI Staff scan completed successfully',
        batchId: result.batchId,
        batchName: result.batchName,
        sourcesChecked: result.sourcesChecked,
        newDraftsCreated: result.newDraftsCreated,
        duplicatesSkipped: result.duplicatesSkipped,
        failedSources: result.failedSources,
        report: result.dailyReport,
      });
    } catch (err: any) {
      console.error('[Cron Error] Scheduled scan failure:', err);
      res.status(500).json({
        success: false,
        error: err.message || 'Scheduled scan failed',
      });
    }
  };

  app.get('/api/cron/ai-staff-scan', handleCronRequest);
  app.post('/api/cron/ai-staff-scan', handleCronRequest);

  app.post('/api/ai-staff/scan', async (req, res) => {
    try {
      const { sources, existingDrafts, existingPosts, settings } = req.body;
      if (!sources || !Array.isArray(sources)) {
        return res.status(400).json({ error: 'Sources array is required for scanning' });
      }

      const { executeSourceScan } = await import('./server/aiStaffScanner');
      const scanResult = await executeSourceScan(
        sources,
        existingDrafts || [],
        existingPosts || [],
        settings || { enabled: true, maxSourcesPerScan: 15, timezone: 'Asia/Kolkata', scanTime: '06:00', autoPublish: false }
      );

      res.json({ success: true, result: scanResult });
    } catch (err: any) {
      console.error('AI Staff Scan error:', err);
      res.status(500).json({
        success: false,
        error: err.message || 'Internal scanner error',
      });
    }
  });

  // Test single source endpoint (POST & GET)
  const handleTestSource = async (req: express.Request, res: express.Response) => {
    try {
      const source = req.body?.source;
      const url = (req.body?.url || req.query.url) as string | undefined;
      if (!source && !url) {
        return res.status(400).json({ error: 'Source object or URL query parameter is required' });
      }
      const { testSingleSource } = await import('./server/sourceDiagnostics');
      const testResult = await testSingleSource(source || url, url);
      res.json({ success: true, result: testResult });
    } catch (err: any) {
      console.error('Test Source error:', err);
      res.status(500).json({ success: false, error: err.message || 'Diagnostic failed' });
    }
  };
  app.post('/api/ai-staff/test-source', handleTestSource);
  app.get('/api/ai-staff/test-source', handleTestSource);

  // Audit all sources endpoint (POST & GET)
  const handleAuditSources = async (req: express.Request, res: express.Response) => {
    try {
      const { sources } = req.body || {};
      const { INITIAL_STAFF_SOURCES } = await import('./src/data/aiStaffDefaults');
      const sourceList = Array.isArray(sources) && sources.length > 0 ? sources : INITIAL_STAFF_SOURCES;
      const { runFullSourceAudit } = await import('./server/sourceDiagnostics');
      const auditResult = await runFullSourceAudit(sourceList);
      res.json({ success: true, result: auditResult });
    } catch (err: any) {
      console.error('Audit Sources error:', err);
      res.status(500).json({ success: false, error: err.message || 'Audit failed' });
    }
  };
  app.post('/api/ai-staff/audit-sources', handleAuditSources);
  app.get('/api/ai-staff/audit-sources', handleAuditSources);

  // Reject unsupported methods or missing endpoints under /api/*
  app.all('/api/*', (req, res) => {
    res.status(404).json({ error: `Endpoint ${req.path} not found` });
  });

  // Serve static files from public directory (e.g. ads.txt, robots.txt, sitemap.xml)
  app.use(express.static(path.join(process.cwd(), 'public')));

  // Vite middleware in dev / Static serving in production
  if (process.env.NODE_ENV !== 'production') {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  // Initialize Background AI Sarkari Staff Daily Scheduler
  try {
    const { initAIScheduler } = await import('./server/aiStaffScheduler');
    initAIScheduler();
  } catch (schedErr) {
    console.warn('[AI Staff Scheduler] Background scheduler init warning:', schedErr);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`All India Sarkari Server running on http://localhost:${PORT}`);
  });
}

startServer();
